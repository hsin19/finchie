"""The Gmail filter that forwards statement e-mails to Finchie, generated from the parsers' claims (ADR 0014).

`task parser:generate` writes it where the backend embeds it; the backend's download puts in the mailbox
address. Run as `python -m finchie_parser.mail_filter OUTPUT`.
"""

import sys
from collections.abc import Sequence
from pathlib import Path
from xml.sax.saxutils import quoteattr

from finchie_parser.parsers import PARSERS, StatementParser

# The backend replaces it with BACKEND_MAILBOX_ADDRESS, which stays out of the repository (ADR 0010).
MAILBOX_PLACEHOLDER = "finchie@mailbox.invalid"
LABEL = "Finchie"


def gmail_query(parsers: Sequence[StatementParser] = PARSERS) -> str:
    """What the filter searches for: each parser's claim, its domains and subject terms. Banks send their
    notices (sign-ins, card applications, campaigns) from the same domains, so a domain is not enough."""
    claims = sorted(
        {(tuple(sorted(parser.sender_domains)), parser.subject_terms) for parser in parsers},
    )
    return " OR ".join(
        f"(from:({' OR '.join(domains)}) subject:({' '.join(f'"{term}"' for term in terms)}))"
        for domains, terms in claims
    )


def gmail_filter(parsers: Sequence[StatementParser] = PARSERS) -> str:
    """One filter, in the format Gmail exports and imports."""
    properties = [
        ("hasTheWord", gmail_query(parsers)),
        ("hasAttachment", "true"),
        ("label", LABEL),
        ("shouldNeverSpam", "true"),
        ("forwardTo", MAILBOX_PLACEHOLDER),
    ]
    lines = [
        "<?xml version='1.0' encoding='UTF-8'?>",
        "<!-- Generated by `task parser:generate` from the parsers' claims (ADR 0014). Do not edit. -->",
        "<feed xmlns='http://www.w3.org/2005/Atom' xmlns:apps='http://schemas.google.com/apps/2006'>",
        "\t<title>Mail Filters</title>",
        "\t<entry>",
        "\t\t<category term='filter'></category>",
        "\t\t<title>Mail Filter</title>",
        "\t\t<content></content>",
        *(f"\t\t<apps:property name={quoteattr(name)} value={quoteattr(value)}/>" for name, value in properties),
        "\t</entry>",
        "</feed>",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: python -m finchie_parser.mail_filter OUTPUT")
    Path(sys.argv[1]).write_text(gmail_filter(), encoding="utf-8")


if __name__ == "__main__":
    main()
